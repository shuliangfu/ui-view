  /**
   * 打开日期面板，点选一个可见日期数字，再点「确定」。
   */
  it("日期选择器可打开、选日并确定", async (t) => {
    if (!t?.browser?.goto) return;
    await sharedEnv.goto(t, DOC_PATH);
    await sharedEnv.waitDocMainReady(t);
    await t.browser.evaluate(() => location.reload());
    await sharedEnv.waitDocMainReady(t);
    await sharedEnv.delay(100);
    const result = await t.browser.evaluate(async () => {
      const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
      const clickEl = (
        el: HTMLElement & { __onclick?: (ev: Event) => void },
      ) => {
        if (typeof el.__onclick === "function") {
          el.__onclick(
            new MouseEvent("click", { bubbles: true, cancelable: true }),
          );
        } else el.click();
      };
      const root = document.querySelector("main [data-ui-datepicker-root]");
      const btn = (root?.querySelector(
        'button[type="button"][aria-haspopup="dialog"]:not([disabled])',
      ) || document.querySelector(
        "main button[aria-haspopup]:not([disabled])",
      )) as (HTMLButtonElement & { __onclick?: (ev: Event) => void }) | null;
      if (!btn) return { ok: false, reason: "no-trigger" };
      btn.scrollIntoView({ block: "center" });
      clickEl(btn);
      let dlg: HTMLElement | null = null;
      for (let i = 0; i < 20; i++) {
        await sleep(50);
        dlg = Array.from(
          document.querySelectorAll('[role="dialog"]'),
        ).find((el) => {
          const r = (el as HTMLElement).getBoundingClientRect();
          return r.width > 20 && r.height > 20;
        }) as HTMLElement | undefined ?? null;
        if (dlg) break;
      }
      if (!dlg) return { ok: false, reason: "no-dialog" };
      let dayCell = dlg.querySelector(
        "button[data-ui-calendar-day]:not([disabled])",
      ) as (HTMLButtonElement & { __onclick?: (ev: Event) => void }) | null;
      if (!dayCell) {
        dayCell = Array.from(dlg.querySelectorAll("button[type='button']"))
          .find(
            (b) =>
              !(b as HTMLButtonElement).disabled &&
              /^\d{1,2}$/.test((b.textContent || "").trim()),
          ) as (HTMLButtonElement & { __onclick?: (ev: Event) => void }) | null;
      }
      if (!dayCell) return { ok: false, reason: "no-day" };
      clickEl(dayCell);
      await sleep(120);
      const okBtn = Array.from(
        dlg.querySelectorAll("button[type='button']"),
      ).find((b) =>
        !(b as HTMLButtonElement).disabled &&
        (b.textContent || "").trim() === "确定"
      ) as
        | (HTMLButtonElement & { __onclick?: (ev: Event) => void })
        | undefined;
      if (!okBtn) return { ok: false, reason: "no-confirm" };
      clickEl(okBtn);
      return { ok: true, reason: "ok" };
    }) as { ok: boolean; reason: string };
    if (!result.ok) throw new Error(`DatePicker: ${JSON.stringify(result)}`);
    expect(result.ok).toBe(true);
  }, DOCS_BROWSER_CONFIG);

  /**
   * 文档小节「基础」：在 main 内定位对应 h3，于该示例区块内完成一次交互。
   */
  it("严格·基础", async (t) => {
    if (!t?.browser?.goto) return;
    await sharedEnv.goto(t, DOC_PATH);
    await sharedEnv.waitDocMainReady(t);
    const ok = await t.browser.evaluate(() => {
      const needle = "基础";
      const main = document.querySelector("main");
      if (!main) return false;
      const heads = main.querySelectorAll("h2, h3");
      for (let i = 0; i < heads.length; i++) {
        const h = heads[i];
        if (!(h.textContent || "").includes(needle)) continue;
        let root: Element | null = h.parentElement;
        for (let depth = 0; depth < 12 && root && root !== main; depth++) {
          const copy = root.querySelector(
            'button[type="button"][aria-label="复制"]',
          ) as HTMLButtonElement | null;
          if (copy && !copy.disabled) {
            copy.click();
            return true;
          }
          const lb = root.querySelector(
            'button[aria-haspopup="listbox"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (lb) {
            lb.click();
            return true;
          }
          const dg = root.querySelector(
            'button[aria-haspopup="dialog"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (dg) {
            dg.click();
            return true;
          }
          const sw = root.querySelector(
            '[role="switch"]',
          ) as HTMLElement | null;
          if (sw && !(sw as HTMLButtonElement).disabled) {
            sw.click();
            return true;
          }
          const cb = root.querySelector(
            'input[type="checkbox"]:not(:disabled)',
          ) as HTMLInputElement | null;
          if (cb) {
            cb.click();
            return true;
          }
          const rd = root.querySelector(
            'input[type="radio"]:not(:disabled)',
          ) as HTMLInputElement | null;
          if (rd) {
            rd.click();
            return true;
          }
          const ta = root.querySelector(
            "textarea:not(:disabled), input:not([type=hidden]):not([type=button]):not([type=submit]):not([type=file]):not([type=checkbox]):not([type=radio]):not(:disabled)",
          ) as HTMLInputElement | null;
          if (ta) {
            ta.focus();
            ta.value = "e2e-strict";
            ta.dispatchEvent(new Event("input", { bubbles: true }));
            return true;
          }
          const rg = root.querySelector(
            'input[type="range"]',
          ) as HTMLInputElement | null;
          if (rg && !rg.disabled) {
            const mx = Number(rg.max) || 100;
            const cur = Number(rg.value) || 0;
            rg.value = String(Math.min(mx, cur + 2));
            rg.dispatchEvent(new Event("input", { bubbles: true }));
            return true;
          }
          const star = root.querySelector(
            '[role="button"][aria-label="3 星"]',
          ) as HTMLElement | null;
          if (star) {
            star.click();
            return true;
          }
          const btn = root.querySelector(
            'button[type="button"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (btn) {
            btn.click();
            return true;
          }
          const a = root.querySelector("a[href]") as HTMLAnchorElement | null;
          if (a) {
            a.click();
            return true;
          }
          root = root.parentElement;
        }
        const box = h.parentElement;
        const txt = box?.innerText?.trim() ?? "";
        return txt.length > 8;
      }
      return false;
    }) as boolean;
    expect(ok).toBe(true);
  }, DOCS_BROWSER_CONFIG);

