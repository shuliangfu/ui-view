  it("级联选择器可展开并完成三级点选", async (t) => {
    if (!t?.browser?.goto) return;
    await sharedEnv.goto(t, DOC_PATH);
    await sharedEnv.waitDocMainReady(t);
    const openOk = await t.browser.evaluate(() => {
      const root = document.querySelector("main [data-ui-cascader-root]");
      const btn = root?.querySelector(
        'button[type="button"][aria-haspopup="dialog"]',
      ) as (HTMLButtonElement & { __onclick?: (ev: Event) => void }) | null;
      if (!btn) return false;
      btn.scrollIntoView({ block: "center" });
      if (typeof btn.__onclick === "function") {
        btn.__onclick(
          new MouseEvent("click", {
            bubbles: true,
            cancelable: true,
            detail: 1,
          }),
        );
      } else btn.click();
      return true;
    }) as boolean;
    expect(openOk).toBe(true);
    await sharedEnv.delay(250);
    /** 在可见浮层内点选，避免命中触发条或隐藏残留面板。 */
    const picked = await t.browser.evaluate(async () => {
      const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
      const visiblePanel = (): HTMLElement | null => {
        const all = Array.from(
          document.querySelectorAll("[data-ui-cascader-panel]"),
        ) as HTMLElement[];
        return all.find((el) => {
          const r = el.getBoundingClientRect();
          const s = getComputedStyle(el);
          return r.width > 20 && r.height > 20 && s.visibility !== "hidden" &&
            s.display !== "none";
        }) ?? null;
      };
      const clickBtn = (b: HTMLElement) => {
        const c = b as HTMLElement & { __onclick?: (ev: Event) => void };
        c.dispatchEvent(
          new MouseEvent("pointerdown", {
            bubbles: true,
            cancelable: true,
            button: 0,
          }),
        );
        if (typeof c.__onclick === "function") {
          c.__onclick(
            new MouseEvent("click", {
              bubbles: true,
              cancelable: true,
              detail: 1,
            }),
          );
        } else c.click();
      };
      const clickLevel = async (name: string) => {
        for (let i = 0; i < 20; i++) {
          const panel = visiblePanel();
          const buttons = panel?.querySelectorAll("button[type=button]") ?? [];
          for (let j = 0; j < buttons.length; j++) {
            const b = buttons[j] as HTMLButtonElement;
            if (b.disabled) continue;
            if ((b.textContent || "").trim() === name) {
              clickBtn(b);
              return true;
            }
          }
          await sleep(50);
        }
        return false;
      };
      if (!await clickLevel("浙江")) return { ok: false, step: "浙江" };
      await sleep(80);
      if (!await clickLevel("杭州")) return { ok: false, step: "杭州" };
      await sleep(80);
      if (!await clickLevel("西湖区")) return { ok: false, step: "西湖区" };
      return { ok: true, step: "ok" };
    }) as { ok: boolean; step: string };
    if (!picked.ok) {
      throw new Error(`Cascader: ${JSON.stringify(picked)}`);
    }
    expect(picked.ok).toBe(true);
  }, DOCS_BROWSER_CONFIG);

  it("严格·静态数据（多级嵌套）", async (t) => {
    if (!t?.browser?.goto) return;
    await sharedEnv.goto(t, DOC_PATH);
    await sharedEnv.waitDocMainReady(t);
    const ok = await t.browser.evaluate(() => {
      const needle = "静态数据（多级嵌套）";
      const main = document.querySelector("main");
      if (!main) return false;
      const heads = main.querySelectorAll("h2, h3");
      for (let i = 0; i < heads.length; i++) {
        const h = heads[i];
        if (!(h.textContent || "").includes(needle)) continue;
        let root: Element | null = h.parentElement;
        for (let depth = 0; depth < 12 && root && root !== main; depth++) {
          const copy = root.querySelector(
            'button[type="button"][aria-label="复制"]',
          ) as HTMLButtonElement | null;
          if (copy && !copy.disabled) {
            copy.click();
            return true;
          }
          const lb = root.querySelector(
            'button[aria-haspopup="listbox"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (lb) {
            lb.click();
            return true;
          }
          const dg = root.querySelector(
            'button[aria-haspopup="dialog"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (dg) {
            dg.click();
            return true;
          }
          const sw = root.querySelector(
            '[role="switch"]',
          ) as HTMLElement | null;
          if (sw && !(sw as HTMLButtonElement).disabled) {
            sw.click();
            return true;
          }
          const cb = root.querySelector(
            'input[type="checkbox"]:not(:disabled)',
          ) as HTMLInputElement | null;
          if (cb) {
            cb.click();
            return true;
          }
          const rd = root.querySelector(
            'input[type="radio"]:not(:disabled)',
          ) as HTMLInputElement | null;
          if (rd) {
            rd.click();
            return true;
          }
          const ta = root.querySelector(
            "textarea:not(:disabled), input:not([type=hidden]):not([type=button]):not([type=submit]):not([type=file]):not([type=checkbox]):not([type=radio]):not(:disabled)",
          ) as HTMLInputElement | null;
          if (ta) {
            ta.focus();
            ta.value = "e2e-strict";
            ta.dispatchEvent(new Event("input", { bubbles: true }));
            return true;
          }
          const rg = root.querySelector(
            'input[type="range"]',
          ) as HTMLInputElement | null;
          if (rg && !rg.disabled) {
            const mx = Number(rg.max) || 100;
            const cur = Number(rg.value) || 0;
            rg.value = String(Math.min(mx, cur + 2));
            rg.dispatchEvent(new Event("input", { bubbles: true }));
            return true;
          }
          const star = root.querySelector(
            '[role="button"][aria-label="3 星"]',
          ) as HTMLElement | null;
          if (star) {
            star.click();
            return true;
          }
          const btn = root.querySelector(
            'button[type="button"]:not([disabled])',
          ) as HTMLButtonElement | null;
          if (btn) {
            btn.click();
            return true;
          }
          const a = root.querySelector("a[href]") as HTMLAnchorElement | null;
          if (a) {
            a.click();
            return true;
          }
          root = root.parentElement;
        }
        const box = h.parentElement;
        const txt = box?.innerText?.trim() ?? "";
        return txt.length > 8;
      }
      return false;
    }) as boolean;
    expect(ok).toBe(true);
  }, DOCS_BROWSER_CONFIG);

